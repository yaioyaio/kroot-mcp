class AIMonitor:
    """
    AI collaboration monitor.

    Tracks AI tool usage and provides effectiveness analysis.
    """

    DETECTION_WINDOW = 3600000  # 1 hour in milliseconds
    SESSION_TIMEOUT = 300000  # 5 minutes in milliseconds

    def __init__(self, event_engine: EventEngine | None = None):
        """
        Initialize the AI monitor.

        Args:
            event_engine: Optional event engine instance.
        """
        self._event_engine = event_engine or get_event_engine()
        self._detections: list[AIUsageDetection] = []
        self._suggestions: dict[str, AISuggestion] = {}
        self._sessions: dict[str, AISession] = {}
        self._active_sessions: dict[AITool, AISession] = {}
        self._detection_rules: dict[AITool, AIDetectionRule] = {}
        self._listeners: dict[str, list[Callable]] = {}
        self._subscription_id: str | None = None

        self._initialize_detection_rules()

    def start(self) -> None:
        """Start the AI monitor and subscribe to events."""
        self._subscription_id = self._event_engine.subscribe(
            "*",
            self._handle_event,
        )

    def stop(self) -> None:
        """Stop the AI monitor."""
        if self._subscription_id:
            self._event_engine.unsubscribe(self._subscription_id)
            self._subscription_id = None

    def on(self, event_type: str, handler: Callable) -> None:
        """Register an event listener."""
        if event_type not in self._listeners:
            self._listeners[event_type] = []
        self._listeners[event_type].append(handler)

    def emit(self, event_type: str, *args: Any) -> None:
        """Emit an event to listeners."""
        if event_type in self._listeners:
            for handler in self._listeners[event_type]:
                try:
                    handler(*args)
                except Exception:
                    pass

